def test_parse_transcript_file_skips_malformed_lines_without_aborting(tmp_path: Path) -> None:
    transcript = tmp_path / "session.jsonl"
    transcript.write_text(
        "not json at all\n"
        + json.dumps(
            {
                "type": "user",
                "message": {"role": "user", "content": "still parses this one"},
                "timestamp": "2026-08-01T00:00:00.000Z",
                "sessionId": "sess-5",
                "promptSource": "typed",
                "origin": {"kind": "human"},
            }
        ),
        encoding="utf-8",
    )
    messages = list(parse_transcript_file(transcript))
    assert len(messages) == 1
    assert messages[0].text == "still parses this one"


def test_parse_transcript_file_drops_non_string_timestamp_without_crashing(
    tmp_path: Path,
) -> None:
    """A non-string timestamp (e.g. a raw epoch int) must not raise -- it's a
    corrupt/unexpected line, and the file's other real messages must still
    parse, matching this function's own "single corrupt line must not abort
    the whole file" guarantee."""
    transcript = tmp_path / "session.jsonl"
    _write_jsonl(
        transcript,
        [
            {
                "type": "user",
                "message": {"role": "user", "content": "bad timestamp type"},
                "timestamp": 1754870400,
                "sessionId": "sess-6",
                "promptSource": "typed",
                "origin": {"kind": "human"},
            },
            {
                "type": "user",
                "message": {"role": "user", "content": "good timestamp"},
                "timestamp": "2026-08-11T00:00:00.000Z",
                "sessionId": "sess-6",
                "promptSource": "typed",
                "origin": {"kind": "human"},
            },
        ],
    )
    messages = list(parse_transcript_file(transcript))
    assert len(messages) == 1
    assert messages[0].text == "good timestamp"


