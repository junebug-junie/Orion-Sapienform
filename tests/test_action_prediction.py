"""Tests for the action-outcome ledger's arithmetic and resolution rules.

Fixtures below are hand-computed from the closed forms in
orion/autonomy/prediction.py's docstring, not captured from a run of the
code under test. A fixture generated by the implementation would pass
against a wrong implementation.
"""

from __future__ import annotations

import math

import pytest

from orion.autonomy.prediction import (
    DEFAULT_OBSERVATION_VARIANCE,
    DEFAULT_PRIOR_VARIANCE,
    EffectPosterior,
    bayesian_surprise_nats,
    score_observation,
    update_posterior,
)


class TestPosteriorUpdate:
    def test_single_update_matches_hand_computed_conjugate_values(self):
        """prior N(0, 0.25), obs 0.5, obs_var 0.04.

        precision = 1/0.25 + 1/0.04 = 4 + 25 = 29  -> var1 = 1/29
        mu1 = (1/29) * (0/0.25 + 0.5/0.04) = 12.5/29
        Both exact rationals, computed by hand from the formula.
        """
        prior = EffectPosterior(mean=0.0, variance=0.25, n=0)
        post = update_posterior(prior, 0.5, observation_variance=0.04)

        assert post.variance == pytest.approx(1.0 / 29.0, rel=1e-12)
        assert post.mean == pytest.approx(12.5 / 29.0, rel=1e-12)
        assert post.n == 1

    def test_update_pulls_toward_observation_but_never_past_it(self):
        prior = EffectPosterior(mean=0.0, variance=0.25, n=3)
        post = update_posterior(prior, 0.5, observation_variance=0.04)
        assert 0.0 < post.mean < 0.5

    def test_variance_strictly_shrinks(self):
        prior = EffectPosterior(mean=0.0, variance=0.25, n=0)
        post = update_posterior(prior, 0.5)
        assert post.variance < prior.variance

    @pytest.mark.parametrize("bad", [float("nan"), float("inf"), float("-inf")])
    def test_non_finite_observation_rejected(self, bad):
        with pytest.raises(ValueError):
            update_posterior(EffectPosterior.cold(), bad)

    @pytest.mark.parametrize("bad", [0.0, -1.0, float("nan")])
    def test_non_positive_observation_variance_rejected(self, bad):
        with pytest.raises(ValueError):
            update_posterior(EffectPosterior.cold(), 0.1, observation_variance=bad)


class TestBayesianSurprise:
    def test_hand_computed_kl_for_one_update(self):
        """KL(N(12.5/29, 1/29) || N(0, 0.25)), natural log, in nats.

        0.5 * ( ln(0.25 / (1/29)) + ((1/29) + (12.5/29)^2)/0.25 - 1 )
        = 0.5 * ( ln(7.25) + 0.881093935790723 - 1 )
        = 0.9310477023286543
        """
        prior = EffectPosterior(mean=0.0, variance=0.25, n=0)
        post = update_posterior(prior, 0.5, observation_variance=0.04)
        assert bayesian_surprise_nats(prior, post) == pytest.approx(
            0.9310477023286543, rel=1e-9
        )

    def test_identical_distributions_are_zero_surprise(self):
        p = EffectPosterior(mean=0.3, variance=0.05, n=7)
        assert bayesian_surprise_nats(p, p) == 0.0

    def test_never_negative(self):
        prior = EffectPosterior(mean=0.4, variance=0.02, n=10)
        post = update_posterior(prior, 0.4, observation_variance=0.04)
        assert bayesian_surprise_nats(prior, post) >= 0.0

    def test_repetition_stops_paying(self):
        """THE load-bearing property of this whole patch.

        An action repeated with a stable outcome must earn monotonically
        less, converging on ~0 -- that is what makes an action Orion has
        taken 7,583 times worth nothing without any hand-written
        anti-repetition rule. Hand-computed sequence for a constant
        observation of 0.5 against the cold prior:

            0.9310477, 0.09414433, 0.0357131, 0.01874212, 0.01153379

        Asserted as a strictly decreasing sequence plus the first two exact
        values, so a change that flattened or inverted the curve fails here
        rather than quietly turning the budget into a repetition subsidy.
        """
        posterior = EffectPosterior.cold()
        surprises = []
        for _ in range(5):
            nxt = update_posterior(posterior, 0.5, observation_variance=0.04)
            surprises.append(bayesian_surprise_nats(posterior, nxt))
            posterior = nxt

        assert surprises[0] == pytest.approx(0.9310477, rel=1e-6)
        assert surprises[1] == pytest.approx(0.09414433, rel=1e-6)
        assert all(a > b for a, b in zip(surprises, surprises[1:])), surprises
        assert surprises[-1] < 0.02

    def test_a_surprising_observation_beats_a_confirming_one(self):
        """Same prior, same n: the outcome that contradicts belief is worth more."""
        prior = EffectPosterior(mean=0.0, variance=0.02, n=20)
        _, confirming, _ = score_observation(prior, 0.0)
        _, surprising, _ = score_observation(prior, 0.8)
        assert surprising > confirming


class TestScoreObservation:
    def test_prediction_error_is_the_raw_residual(self):
        prior = EffectPosterior(mean=0.2, variance=0.1, n=4)
        _, _, error = score_observation(prior, 0.5)
        assert error == pytest.approx(0.3)

    def test_defaults_are_the_disclosed_constants(self):
        """Guards the provenance claim in the module docstring.

        These are derived from 68,715 real pressure_delta observations
        (pooled sd ~0.2); if someone retunes them the docstring's measured
        table has to be retaken, so make the change loud.
        """
        assert DEFAULT_OBSERVATION_VARIANCE == pytest.approx(0.2**2)
        assert DEFAULT_PRIOR_VARIANCE == pytest.approx(0.5**2)
        assert DEFAULT_PRIOR_VARIANCE > DEFAULT_OBSERVATION_VARIANCE

    def test_cold_prior_is_wide_enough_for_data_to_dominate_quickly(self):
        """After 3 observations of 0.4 the data must already dominate.

        Hand-computed: precisions add, so the posterior mean is the
        precision-weighted average of prior mean (0.0, weight 1/0.25 = 4)
        and the data (0.4, weight 3/0.04 = 75):

            0.4 * 75 / (75 + 4) = 30/79 = 0.3797468354430379

        i.e. 95% of the way to the data after three samples. Asserted
        exactly rather than as "close to 0.4" -- the residual prior pull is
        real and a test that hid it would also hide a prior widened until it
        stopped regularising anything.
        """
        posterior = EffectPosterior.cold()
        for _ in range(3):
            posterior = update_posterior(posterior, 0.4)
        assert posterior.mean == pytest.approx(30.0 / 79.0, rel=1e-12)
        assert posterior.mean / 0.4 > 0.94

    def test_sd_matches_variance(self):
        assert EffectPosterior(mean=0.0, variance=0.09, n=1).sd == pytest.approx(0.3)
        assert math.isfinite(EffectPosterior.cold().sd)
