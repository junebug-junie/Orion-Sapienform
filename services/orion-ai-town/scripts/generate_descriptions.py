#!/usr/bin/env python3
"""Deterministically compose AI Town `Descriptions` from the tracked card set.

Source of truth: ``services/orion-ai-town/cards/town_cards.local.yaml`` when it
exists (gitignored: the real cards, which carry personal details), else the
committed, redacted ``town_cards.yaml`` example. Outputs follow the source: the
local cards write ``generated/*.local.txt`` (gitignored), the example writes the
tracked ``generated/*.txt``, so real text never lands in a tracked file.
Target: ``services/orion-ai-town/upstream/data/characters.ts`` (the ``Descriptions``
array only; imports + ``characters`` sprite table are left untouched).

NPC identities are the rich, prompt-injected self-descriptions read by
``convex/agent/conversation.ts`` at prompt time. Juniper (human) and Orion
(external join) are NOT emitted here — Juniper's sprite + blurb go in
``convex/world.ts`` and Orion's card is applied by the embodiment bootstrap.

Run from repo root:  python services/orion-ai-town/scripts/generate_descriptions.py
Idempotent: re-running with unchanged cards produces an unchanged file.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

_HERE = Path(__file__).resolve()
_SERVICE = _HERE.parents[1]
CARDS_EXAMPLE = _SERVICE / "cards" / "town_cards.yaml"
CARDS_LOCAL = _SERVICE / "cards" / "town_cards.local.yaml"
CHARACTERS_TS = _SERVICE / "upstream" / "data" / "characters.ts"
WORLD_TS = _SERVICE / "upstream" / "convex" / "world.ts"
CONSTANTS_TS = _SERVICE / "upstream" / "convex" / "constants.ts"
GENERATED = _SERVICE / "cards" / "generated"
HUMAN_PATCH = _SERVICE / "patches" / "orion-human-juniper.patch"
# Simulation seed (cards' sim_world + per-character sim blocks). The committed
# overlay copy is rendered from the redacted example; apply_upstream_patches.sh
# re-renders it into upstream/ from whichever cards are the source.
OVERLAY_SIM_SEED = _SERVICE / "overlay" / "convex" / "sim" / "seed.ts"
SIM_KEYS = ("home", "work", "schedule", "needs", "cash", "wage", "purpose_weights", "lying_rate")
# The committed human patch carries this token in place of Juniper's join
# description; scripts/apply_upstream_patches.sh renders it from the cards.
HUMAN_DESCRIPTION_TOKEN = "__ORION_TOWN_HUMAN_DESCRIPTION__"


def cards_path() -> Path:
    """Local real cards first, committed redacted example second."""
    return CARDS_LOCAL if CARDS_LOCAL.exists() else CARDS_EXAMPLE


def load_cards() -> dict:
    return yaml.safe_load(cards_path().read_text(encoding="utf-8"))


def generated_name(stem: str) -> str:
    """``<stem>.local.txt`` when the real cards are the source, else ``<stem>.txt``."""
    return f"{stem}.local.txt" if cards_path() == CARDS_LOCAL else f"{stem}.txt"


def render_human_patch(cards: dict) -> str:
    """The human-join patch with Juniper's description filled in from the cards."""
    by_id = {c["id"]: c for c in cards["characters"]}
    desc = _ts_backtick(compose_presence_blurb(by_id["juniper_feld"]))
    text = HUMAN_PATCH.read_text(encoding="utf-8")
    if HUMAN_DESCRIPTION_TOKEN not in text:
        raise SystemExit(f"{HUMAN_PATCH.name}: missing {HUMAN_DESCRIPTION_TOKEN}")
    return text.replace(HUMAN_DESCRIPTION_TOKEN, desc)

def _sim_source(cards: dict) -> tuple[dict, dict]:
    """sim_world + {character id: sim block}. Local cards written before the
    sim blocks existed borrow them from the example (they hold no personal
    details), so a stale local file still seeds a working world."""
    example = None
    world = cards.get("sim_world")
    blocks = {c["id"]: c.get("sim") for c in cards["characters"]}
    if world is None or any(b is None for b in blocks.values()):
        example = yaml.safe_load(CARDS_EXAMPLE.read_text(encoding="utf-8"))
        ex_blocks = {c["id"]: c.get("sim") for c in example["characters"]}
        world = world if world is not None else example["sim_world"]
        blocks = {cid: b if b is not None else ex_blocks.get(cid) for cid, b in blocks.items()}
    return world, blocks


def render_sim_seed(cards: dict) -> str:
    """overlay/convex/sim/seed.ts: the Cast that core.createState seeds from."""
    world, blocks = _sim_source(cards)
    characters = []
    for card in cards["characters"]:
        sim = blocks.get(card["id"])
        if sim is not None:
            missing = [k for k in SIM_KEYS if k not in sim]
            if missing:
                raise SystemExit(f"{card['id']}: sim block missing {', '.join(missing)}")
            sim = {**sim, "stock": dict(sim.get("stock") or {})}
        characters.append({"id": card["id"], "name": card["name"], "sim": sim})
    cast = {
        "places": {pid: {"name": name} for pid, name in world["places"].items()},
        "place_stock": world.get("place_stock") or {},
        "facts": world.get("facts") or {},
        "characters": characters,
    }
    seed = int(world["seed"])
    return (
        "// GENERATED by scripts/generate_descriptions.py from the cards' sim blocks.\n"
        "// Do not edit: change cards/town_cards*.yaml and re-run the generator.\n"
        "import type { Cast } from './core';\n\n"
        f"export const SIM_SEED = {seed};\n\n"
        f"export const SIM_CAST: Cast = {json.dumps(cast, indent=2, sort_keys=True)};\n"
    )


# Fixed NPC order (matches the seeded roster / sprite table).
NPC_ORDER = ["mara_vale", "nico_sable", "sofia_bell", "cam_lin"]


def _collapse(text: str | None) -> str:
    return " ".join((text or "").split())


def compose_identity(card: dict) -> str:
    """Job-first identity: role, style, today's loop, objects, one-sentence pressure."""
    name = str(card.get("name") or "They").strip()
    role = _collapse(card.get("role"))
    style = _collapse(card.get("conversation_style"))
    loop = card.get("daily_loop") or []
    today = _collapse(loop[0]) if loop else ""
    parts = [
        f"{name} is the town's {role}." if role else "",
        style,
        f"Today: {today}." if today else "",
        _collapse(card.get("public_description")),
    ]
    pressure = _collapse(card.get("private_pressure"))
    if pressure:
        first = pressure.split(".")[0].strip()
        parts.append(first + "." if first and not first.endswith(".") else first)
    dynamic = _collapse(card.get("orion_dynamic"))
    if dynamic:
        first = dynamic.split(".")[0].strip()
        parts.append(first + "." if first and not first.endswith(".") else first)
    return " ".join(p for p in parts if p)


def compose_presence_blurb(card: dict) -> str:
    """Rich blurb for players seeded outside `Descriptions` (Juniper human join,
    Orion external join). Uses public_description + deeper_bio + town_presence +
    signature so residents perceive a full character, not a one-liner."""
    parts = [
        _collapse(card.get("public_description")),
        _collapse(card.get("deeper_bio")),
        _collapse(card.get("town_presence")),
    ]
    signature = _collapse(card.get("signature_line"))
    if signature:
        parts.append(f"A line {_signature_intro(card.get('pronouns'))}: {signature}")
    return " ".join(p for p in parts if p)


# Subject pronoun -> (word, verb) for "A line <subject> often <verb>:". Singular
# they takes the plural verb form ("they often use"); she/he take "uses".
_SUBJECT_VERB = {
    "she": ("she", "uses"),
    "he": ("he", "uses"),
    "they": ("they", "use"),
}


def _signature_intro(pronouns: str | None) -> str:
    subject = str(pronouns or "they/them").split("/", 1)[0].strip().lower()
    word, verb = _SUBJECT_VERB.get(subject, ("they", "use"))
    return f"{word} often {verb}"


def _ts_backtick(text: str) -> str:
    # Template-literal safe: escape backslash, backtick, and ${ interpolation.
    return text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def render_descriptions(cards: dict) -> str:
    by_id = {c["id"]: c for c in cards["characters"]}
    sprites = cards["sprites"]
    plans = cards["plans"]
    lines = ["export const Descriptions = ["]
    for cid in NPC_ORDER:
        card = by_id[cid]
        identity = _ts_backtick(compose_identity(card))
        plan = _ts_backtick(_collapse(plans[cid]))
        lines.append("  {")
        lines.append(f"    name: {_ts_single(card['name'])},")
        lines.append(f"    character: '{sprites[cid]}',")
        lines.append(f"    identity: `{identity}`,")
        lines.append(f"    plan: `{plan}`,")
        lines.append("  },")
    lines.append("];")
    return "\n".join(lines)


def _ts_single(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


# Real join description in world.ts (start-of-line, not the `// description:` comment).
_WORLD_DESC_RE = re.compile(
    r"(?m)^(?P<indent>[ \t]*)description: `(?:[^`\\]|\\.)*`,$"
)
_WORLD_CHAR_RE = re.compile(r"(?m)^(?P<indent>[ \t]*)character: .*,$")
_DEFAULT_NAME_RE = re.compile(r"(?m)^export const DEFAULT_NAME = '(?:[^'\\]|\\.)*';$")


def patch_juniper(cards: dict) -> list[str]:
    """Splice Juniper (human player) into constants.ts (DEFAULT_NAME) and
    world.ts (join sprite + description) so those patches are reproducible
    from the cards. Returns the list of changed file labels."""
    by_id = {c["id"]: c for c in cards["characters"]}
    juniper = by_id["juniper_feld"]
    sprite = cards["sprites"]["juniper_feld"]
    changed: list[str] = []

    const_src = CONSTANTS_TS.read_text(encoding="utf-8")
    new_const, n = _DEFAULT_NAME_RE.subn(
        f"export const DEFAULT_NAME = {_ts_single(juniper['name'])};", const_src
    )
    if n != 1:
        raise SystemExit(f"constants.ts: expected 1 DEFAULT_NAME, found {n}")
    if new_const != const_src:
        CONSTANTS_TS.write_text(new_const, encoding="utf-8")
        changed.append("convex/constants.ts")

    world_src = WORLD_TS.read_text(encoding="utf-8")
    new_world, n = _WORLD_CHAR_RE.subn(
        lambda m: f"{m.group('indent')}character: '{sprite}',", world_src, count=1
    )
    if n != 1:
        raise SystemExit(f"world.ts: expected 1 join character, found {n}")
    desc = _ts_backtick(compose_presence_blurb(juniper))
    new_world, n = _WORLD_DESC_RE.subn(
        lambda m: f"{m.group('indent')}description: `{desc}`,", new_world, count=1
    )
    if n != 1:
        raise SystemExit(f"world.ts: expected 1 join description, found {n}")
    if new_world != world_src:
        WORLD_TS.write_text(new_world, encoding="utf-8")
        changed.append("convex/world.ts")
    return changed


def main() -> int:
    if sys.argv[1:2] == ["--render-human-patch"]:
        sys.stdout.write(render_human_patch(load_cards()))
        return 0
    if sys.argv[1:2] == ["--render-sim-seed"]:
        sys.stdout.write(render_sim_seed(load_cards()))
        return 0
    cards = load_cards()
    print(f"cards: {cards_path().relative_to(_SERVICE.parents[1])}")
    src = CHARACTERS_TS.read_text(encoding="utf-8")

    start = src.index("export const Descriptions = [")
    end_marker = "export const characters ="
    end = src.index(end_marker)
    # keep everything after the Descriptions array closes, before `characters`
    tail = src[end:]
    head = src[:start]
    new_block = render_descriptions(cards)
    new_src = f"{head}{new_block}\n\n{tail}"
    if new_src != src:
        CHARACTERS_TS.write_text(new_src, encoding="utf-8")
        print(f"updated {CHARACTERS_TS.relative_to(_SERVICE.parents[1])}")
    else:
        print("characters.ts already up to date")

    # Emit generated blurbs for players seeded outside `Descriptions`:
    #  - orion_town_card.txt   -> consumed by the embodiment bootstrap
    #  - juniper_description.txt -> reference for the world.ts join description
    by_id = {c["id"]: c for c in cards["characters"]}
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / generated_name("orion_town_card")).write_text(
        compose_presence_blurb(by_id["orion"]) + "\n", encoding="utf-8"
    )
    (GENERATED / generated_name("juniper_description")).write_text(
        compose_presence_blurb(by_id["juniper_feld"]) + "\n", encoding="utf-8"
    )
    print(f"wrote {GENERATED.relative_to(_SERVICE.parents[1])}/{generated_name('orion_town_card')}")

    # Simulation seed. Only the redacted example refreshes the tracked overlay
    # copy; the real cards reach upstream/ through apply_upstream_patches.sh.
    if cards_path() == CARDS_EXAMPLE:
        seed_src = render_sim_seed(cards)
        if not OVERLAY_SIM_SEED.exists() or OVERLAY_SIM_SEED.read_text(encoding="utf-8") != seed_src:
            OVERLAY_SIM_SEED.write_text(seed_src, encoding="utf-8")
            print(f"updated {OVERLAY_SIM_SEED.relative_to(_SERVICE.parents[1])}")

    # Juniper (human) join description + DEFAULT_NAME in the Convex source.
    juniper_changed = patch_juniper(cards)
    for label in juniper_changed:
        print(f"updated upstream/{label}")
    if not juniper_changed:
        print("world.ts/constants.ts already up to date")

    # sanity: count rendered NPC entries directly (indentation-independent)
    n = new_block.count("\n    character: '")
    print(f"Descriptions entries: {n}")
    return 0 if n == len(NPC_ORDER) else 1


if __name__ == "__main__":
    raise SystemExit(main())
