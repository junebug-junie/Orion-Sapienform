def test_iter_all_human_messages_walks_every_file_under_root(tmp_path: Path) -> None:
    (tmp_path / "proj-a").mkdir()
    (tmp_path / "proj-b").mkdir()
    _write_jsonl(
        tmp_path / "proj-a" / "s1.jsonl",
        [
            {
                "type": "user",
                "message": {"role": "user", "content": "from proj a"},
                "timestamp": "2026-08-01T00:00:00.000Z",
                "sessionId": "s1",
                "promptSource": "typed",
                "origin": {"kind": "human"},
            }
        ],
    )
    _write_jsonl(
        tmp_path / "proj-b" / "s2.jsonl",
        [
            {
                "type": "user",
                "message": {"role": "user", "content": "from proj b"},
                "timestamp": "2026-08-01T00:00:00.000Z",
                "sessionId": "s2",
                "promptSource": "typed",
                "origin": {"kind": "human"},
            }
        ],
    )
    messages = list(iter_all_human_messages(tmp_path))
    assert {m.text for m in messages} == {"from proj a", "from proj b"}
