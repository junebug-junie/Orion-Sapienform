"""Install a pinned, local NES preflight kit. No system packages or services changed."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

from .pad_lab import build_rom
from .probe import digest

SOURCE_URL = "https://github.com/libretro/libretro-fceumm.git"
SOURCE_COMMIT = "ac0d00a7fc01166f84c7bac01d1084ebfd2b865e"
RUNNER_IMAGE = "python@sha256:0a310eeecf4e1f5a0743f9a6520c90c88d089c903ca5fd283f501e3a805f5f89"
DEFAULT_ROOT = Path.home() / ".local/share/orion/retro"


def command(args, **kwargs):
    return subprocess.run(args, check=True, text=True, **kwargs)


def install_bytes(path, data):
    """Idempotent installation; never overwrite a different existing artifact."""
    if path.exists():
        if path.read_bytes() != data:
            raise ValueError(f"existing artifact differs: {path}")
        return
    with path.open("xb") as stream:
        stream.write(data)


def install_runtime(root):
    """Retain versioned probe source so the kit outlives a development worktree."""
    source = Path(__file__).parent
    files = {path.name: path.read_bytes() for path in sorted(source.glob("*.py"))}
    files["PAD_LAB_LICENSE"] = (source / "PAD_LAB_LICENSE").read_bytes()
    identity = hashlib.sha256()
    for name, data in sorted(files.items()):
        identity.update(name.encode() + b"\0" + hashlib.sha256(data).digest())
    relative = f"runtime/{identity.hexdigest()}"
    package = root / relative / "orion/retro"
    package.mkdir(parents=True, exist_ok=True, mode=0o700)
    install_bytes(package.parent / "__init__.py", b'"""Installed offline retro kit."""\n')
    for name, data in files.items():
        install_bytes(package / name, data)
    launcher = ("# Generated by Orion retro setup; runtime revisions are retained.\n"
                "from pathlib import Path\nimport json\nimport sys\n"
                "root = Path(__file__).resolve().parent\n"
                "manifest = json.loads((root / 'manifest.json').read_text())\n"
                "runtime = (root / manifest['runtime']).resolve(strict=True)\n"
                "if not runtime.is_relative_to(root / 'runtime'):\n"
                "    raise ValueError('runtime must be inside the kit runtime directory')\n"
                "sys.path.insert(0, str(runtime))\n"
                "from orion.retro.local_runner import main\n"
                "sys.argv.extend(['--root', str(root)])\n"
                "raise SystemExit(main())\n")
    with tempfile.NamedTemporaryFile("w", dir=root, delete=False) as stream:
        stream.write(launcher)
        temporary = stream.name
    os.replace(temporary, root / "run.py")
    return relative


def setup(root):
    root = root.expanduser().resolve()
    for tool in ("git", "make", "cc", "docker"):
        if not shutil.which(tool):
            raise RuntimeError(f"required build tool unavailable: {tool}")
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    for directory in ("sources", "cores", "roms", "licenses", "evidence"):
        (root / directory).mkdir(exist_ok=True, mode=0o700)
    source = root / "sources" / f"fceumm-{SOURCE_COMMIT[:8]}"
    if not source.exists():
        command(["git", "clone", "--no-checkout", SOURCE_URL, str(source)])
        command(["git", "checkout", "--detach", SOURCE_COMMIT], cwd=source)
    actual = command(["git", "rev-parse", "HEAD"], cwd=source, capture_output=True).stdout.strip()
    dirty = command(["git", "status", "--porcelain", "--untracked-files=no"],
                    cwd=source, capture_output=True).stdout.strip()
    if actual != SOURCE_COMMIT or dirty:
        raise ValueError("core source is not clean at the pinned revision")
    # Two compiler jobs maximum; no sudo, package install or host emulator launch.
    with (root / "evidence/build.log").open("w") as log:
        command(["make", "-f", "Makefile.libretro", "clean"], cwd=source,
                stdout=log, stderr=subprocess.STDOUT)
        command(["make", "-f", "Makefile.libretro", "-j2"], cwd=source,
                stdout=log, stderr=subprocess.STDOUT)
    core = root / "cores" / f"fceumm-{SOURCE_COMMIT[:8]}.so"
    rom = root / "roms/orion-pad-lab-v1.nes"
    install_bytes(core, (source / "fceumm_libretro.so").read_bytes())
    install_bytes(rom, build_rom())
    install_bytes(root / "licenses/FCEUmm-GPL-2.0.txt", (source / "Copying").read_bytes())
    install_bytes(root / "licenses/Pad-Lab-MIT.txt", Path(__file__).with_name("PAD_LAB_LICENSE").read_bytes())
    command(["docker", "pull", RUNNER_IMAGE])
    runtime = install_runtime(root)
    manifest = {
        "runtime": runtime,
        "schema_version": "retro.local_setup.v1",
        "source_url": SOURCE_URL, "source_commit": SOURCE_COMMIT,
        "core": str(core.relative_to(root)), "core_sha256": digest(core),
        "rom": str(rom.relative_to(root)), "rom_sha256": digest(rom),
        "runner_image": RUNNER_IMAGE,
        "build_commands": [["make", "-f", "Makefile.libretro", "clean"],
                           ["make", "-f", "Makefile.libretro", "-j2"]],
        "compiler": command(["cc", "--version"], capture_output=True).stdout.splitlines()[0],
        "rom_generator_sha256": digest(Path(__file__).with_name("pad_lab.py")),
        "licenses": ["licenses/FCEUmm-GPL-2.0.txt", "licenses/Pad-Lab-MIT.txt"],
        "scope": "offline NES diagnostic; no Hub, agent policy or commercial ROMs",
    }
    # Publish only after successful build, input checks and image availability.
    target = root / "manifest.json"
    with tempfile.NamedTemporaryFile("w", dir=root, delete=False) as stream:
        json.dump(manifest, stream, indent=2)
        stream.write("\n")
        temporary = stream.name
    os.replace(temporary, target)
    print(target)
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    args = parser.parse_args()
    setup(args.root)


if __name__ == "__main__":
    main()
