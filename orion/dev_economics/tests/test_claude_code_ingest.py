def _user_line(*, ts: str, text: str, prompt_source: str | None = "typed") -> dict:
    line = {
        "type": "user",
        "message": {"role": "user", "content": text},
        "timestamp": ts,
        "sessionId": "sess-denominator",
        "origin": {"kind": "human"},
    }
    if prompt_source is not None:
        line["promptSource"] = prompt_source
    return line


